# Optional remote bash prompt injection.

function ConvertTo-SshBashAnsi {
    param([string]$Color)
    if (-not (Test-SshHexColor $Color)) { return '' }
    $rgb = Convert-SshHexToRgb -Color $Color
    return "\[\e[38;2;$($rgb.R);$($rgb.G);$($rgb.B)m\]"
}

function Get-SshRemoteThemeScript {
    [CmdletBinding()]
    param(
        [Parameter(Position = 0)][string]$Type,
        $Settings
    )

    if (-not $Settings) { $Settings = Get-SshSettings }
    if ([string]::IsNullOrWhiteSpace($Type)) {
        $Type = [string](Get-SshValue $Settings 'defaultTheme' 'local')
    }

    $theme = Get-SshThemeByName -Name $Type
    $promptSettings = Get-SshValue $Settings 'prompt' @{}
    $icon = if (Test-SshPromptIcons -Settings $Settings) { Get-SshThemeIcon -Theme $theme -Settings $Settings } else { '' }
    $showDeviceName = [bool](Get-SshValue $promptSettings 'deviceName' $false)
    $showDevice = [bool](Get-SshValue (Get-SshValue $Settings 'show' @{}) 'device' $true)

    $deviceText = ''
    if ($showDevice) {
        if ($icon -and $showDeviceName) { $deviceText = "$icon $($theme.BadgeText)" }
        elseif ($icon) { $deviceText = $icon }
        elseif ($showDeviceName) { $deviceText = $theme.BadgeText }
    }

    $reset = '\[\e[0m\]'
    $devicePart = if ($deviceText) { "$(ConvertTo-SshBashAnsi -Color $theme.Accent2)$deviceText$reset " } else { '' }
    $scriptBody = @'
# Generated by SshThemes for __LABEL__.
# Installed at ~/.config/sshthemes/rc. Remove this file to undo.
[ -f ~/.bashrc ] && . ~/.bashrc

__ssht_prompt() {
  local st=$?
  local git_branch=''
  if command -v git >/dev/null 2>&1 && git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    git_branch=" $(git branch --show-current 2>/dev/null)"
  fi
  local exit_part=''
  if [ "$st" -ne 0 ]; then
    exit_part=" __EXITFG__[$st]__RESET__"
  fi
  PS1="\n__DEVICE____ACCENT__\u__RESET__@__HOSTFG__\h__RESET__ __PATHFG__\w__RESET____GITFG__${git_branch}__RESET__${exit_part}\n__ACCENT__> __RESET__"
}
PROMPT_COMMAND="__ssht_prompt${PROMPT_COMMAND:+;$PROMPT_COMMAND}"
'@

    $scriptBody = $scriptBody.Replace('__LABEL__', $theme.Label)
    $scriptBody = $scriptBody.Replace('__DEVICE__', $devicePart)
    $scriptBody = $scriptBody.Replace('__ACCENT__', (ConvertTo-SshBashAnsi -Color $theme.Accent))
    $scriptBody = $scriptBody.Replace('__ACCENT2__', (ConvertTo-SshBashAnsi -Color $theme.Accent2))
    $scriptBody = $scriptBody.Replace('__HOSTFG__', (ConvertTo-SshBashAnsi -Color $theme.Prompt.host))
    $scriptBody = $scriptBody.Replace('__PATHFG__', (ConvertTo-SshBashAnsi -Color $theme.Prompt.path))
    $scriptBody = $scriptBody.Replace('__GITFG__', (ConvertTo-SshBashAnsi -Color $theme.Prompt.git))
    $scriptBody = $scriptBody.Replace('__EXITFG__', (ConvertTo-SshBashAnsi -Color $theme.Prompt.exitFail))
    $scriptBody = $scriptBody.Replace('__RESET__', $reset)

    return $scriptBody
}

function Install-SshRemoteTheme {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory, Position = 0)][string]$Target,
        [string]$Type,
        [string]$User,
        [int]$Port,
        [string]$IdentityFile,
        [switch]$PassThru
    )

    $resolved = Resolve-SshTarget -Target $Target -User $User -Port $Port -IdentityFile $IdentityFile
    if ($resolved.IsS3) { throw 'Tema remoto nao se aplica a s3://. Use awsx para o workspace S3.' }

    if (-not $Type) {
        $detected = Resolve-SshDeviceType -Target $Target
        $Type = $detected.Type
    }

    $settings = Get-SshSettings
    $remoteSettings = Get-SshValue $settings 'remote' @{}
    $rcPath = [string](Get-SshValue $remoteSettings 'rcPath' '~/.config/sshthemes/rc')
    $scriptText = Get-SshRemoteThemeScript -Type $Type -Settings $settings
    $base64 = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($scriptText))

    $sshCommand = Get-Command ssh -ErrorAction SilentlyContinue
    if (-not $sshCommand) { throw 'Cliente ssh nao encontrado no PATH.' }

    $remoteCommand = "mkdir -p `$(dirname $rcPath) && printf %s '$base64' | base64 -d > $rcPath && echo __SSHT_OK__"
    $sshArguments = @()
    if ($resolved.Port) { $sshArguments += @('-p', [string]$resolved.Port) }
    if ($resolved.IdentityFile) { $sshArguments += @('-i', $resolved.IdentityFile) }
    $sshArguments += $resolved.SshTarget
    $sshArguments += $remoteCommand

    $output = (& $sshCommand.Source @sshArguments 2>&1 | Out-String)
    if ($output -notmatch '__SSHT_OK__') {
        throw "Falha ao instalar o tema remoto: $($output.Trim())"
    }

    Write-Host "Tema remoto '$Type' instalado em $rcPath ($($resolved.SshTarget))." -ForegroundColor DarkGray
    Write-Host "Conecte com: sshx $Target -RemoteTheme" -ForegroundColor DarkGray

    if ($PassThru) {
        return [pscustomobject]@{
            Target   = $resolved.SshTarget
            Type     = $Type
            RcPath   = $rcPath
            Script   = $scriptText
        }
    }
}
